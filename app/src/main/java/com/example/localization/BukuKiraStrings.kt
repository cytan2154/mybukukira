  fun translateAccount(keyMs: String, lang: LanguageCode): String {
    return when (lang) {
      LanguageCode.MS -> keyMs
      LanguageCode.EN -> ledgerTranslationsEn[keyMs] ?: keyMs
      LanguageCode.ZH -> ledgerTranslationsZh[keyMs] ?: keyMs
    }
  }

  fun formatAmount(amount: Double): String {
    val symbols = DecimalFormatSymbols(Locale.US)
    val df = DecimalFormat("#,##0.00", symbols)
    return if (amount < 0) "-${df.format(-amount)}" else df.format(amount)
  }

  fun formatCurrency(currency: String, amount: Double): String {
    val symbols = DecimalFormatSymbols(Locale.US)
    val df = DecimalFormat("#,##0.00", symbols)
    return if (amount < 0) {
      "-$currency ${df.format(-amount)}"
    } else {
      "$currency ${df.format(amount)}"
    }
  }

